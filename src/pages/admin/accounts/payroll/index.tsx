interface Employee {
    _id: string;
    name: string;
    role: string;
    details?: {
        mileRate?: number;
        hourlyRate?: number;
        baseSalary?: number;
        [key: string]: any;
    };
}






interface Payroll {
    _id: string;
    userId: {
        _id: string;
        name: string;
        role: string;
        internalId?: string;
    };
    baseSalary: number;
    bonus: number;
    deductions: number;
    totalSalary: number;
    payDate: string;
    startDate: string;
    endDate: string;
    createdAt: string;
    // Tax fields
    country?: string;
    // Canada taxes
    federalIncomeTaxCA?: number;
    provincialIncomeTaxCA?: number;
    cpp?: number;
    ei?: number;
    provincialHealthTaxCA?: number;
    // USA taxes
    federalIncomeTaxUS?: number;
    stateIncomeTaxUS?: number;
    socialSecurityTax?: number;
    medicareTax?: number;
    stateDisabilityInsurance?: number;
    localTax?: number;
    // Driver-specific fields
    trips?: Array<{
        _id: string;
        tripNumber?: string;
        startLocation?: {
            place?: string;
            latitude?: string;
            longitude?: string;
        };
        endLocation?: {
            place?: string;
            latitude?: string;
            longitude?: string;
        };
        actualEndDate?: string;
        distance?: number;
        distanceInMiles?: number;
        earnings?: string;
    }>;
    loads?: Array<{
        _id: string;
        details?: {
            internalId?: string;
        };
        route?: {
            multipleDropOffs?: boolean;
            selectPickup?: {
                place?: string;
                latitude?: string;
                longitude?: string;
            };
            selectDropOff?: {
                place?: string;
                latitude?: string;
                longitude?: string;
            };
            wayPoints?: Array<{
                address: {
                    place: string;
                    latitude: string;
                    longitude: string;
                };
            }>;
        };
        assignedAt?: string;
        startedAt?: string;
        completedAt?: string;
    }>;
    totalMiles?: number;
    ratePerMile?: number;
    // Employee attendance fields (optional)
    totalHours?: number;
    regularHours?: number;
    overtimeHours?: number;
    hourlyRate?: number;
    presentDays?: number;
    absentDays?: number;
}

